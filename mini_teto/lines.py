_bags = {}
_last = {}


def pick(lang, key):
    """A random line, but never the same one twice before the rest have had their turn."""
    pool = LINES[lang][key]
    if len(pool) < 5:
        return random.choice(pool)
    k = (lang, key)
    bag = _bags.get(k)
    if not bag:
        bag = list(range(len(pool)))
        random.shuffle(bag)
        if bag[-1] == _last.get(k):
            bag[0], bag[-1] = bag[-1], bag[0]
        _bags[k] = bag
    _last[k] = bag.pop()
    return pool[_last[k]]


def fill(text, **values):
    for k, v in values.items():
        text = text.replace("{" + k + "}", str(v))
    return text
